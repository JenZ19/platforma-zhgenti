function mentions(step: QuestStep, ...words: string[]): boolean {
  const text = `${step.title} ${step.action} ${step.expected.join(" ")}`.toLowerCase();
  return words.some((word) => text.includes(word));
}

/**
 * Типовые поломки этого шага. Не заменяют помощь по квесту: это короткий список того,
 * что чаще всего идёт не так именно на таком шаге, чтобы не ждать ответа куратора.
 */
export function troublesFor(step: QuestStep, project: ProjectDefinition): Trouble[] {
  const list: Trouble[] = [];
  if (project.journey === "setup") list.push(...setupTroubles);
  if (step.links?.some((link) => link.href.endsWith(".zip"))) list.push(...zipTroubles);
  if (step.kind === "prompt") list.push(...promptTroubles);
  if (mentions(step, "ссылк", "опублик", "телефон")) list.push(...linkTroubles);
  return list.slice(0, 4);
}
