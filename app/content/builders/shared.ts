const rewardAt: Record<number, string> = {
  4: "Хранительница проекта",
  8: "Фея работающего сценария",
  12: "Хранительница безопасной версии",
  17: "Фея готового портфолио",
};

function shot(project: ProjectDefinition, id: number) {
  return `/screens/${project.slug}/step-${String(id).padStart(2, "0")}.webp`;
}

function demo(project: ProjectDefinition, index: number) {
  return project.demo[index % project.demo.length];
}

function feature(project: ProjectDefinition, index: number) {
  return project.features[index % project.features.length];
}

function entity(project: ProjectDefinition, index: number) {
  return project.entities[index % project.entities.length];
}

function makeStep(
  project: ProjectDefinition,
  id: number,
  title: string,
  eyebrow: string,
  why: string,
  action: string,
  prompt: string,
  expected: string[],
  helpTitle: string,
  helpBody: string,
  helpPrompt: string,
): QuestStep {
  return {
    id,
    title,
    eyebrow,
    why,
    action,
    kind: "prompt",
    prompt,
    expected,
    screenshot: shot(project, id),
    reward: rewardAt[id],
    help: { title: helpTitle, body: helpBody, prompt: helpPrompt },
  };
}

