function actionFor(step: number): MobileAction {
  if (step === 13) return { tool: "screenshot", label: "Отправить мобильную проверку Фее", note: "Пришлите первый экран, форму расхода и новый остаток." };
  if (step === 14) return { tool: "lovable", label: "Открыть публикацию", href: "https://lovable.dev/", note: "Откройте уже созданный проект и нажмите публикацию только после проверки." };
  return {
    tool: "telegram",
    label: step === 15 ? "Создать клиентскую копию" : step === 16 ? "Отправить бриф заказчика" : step === 17 ? "Получить карточку портфолио" : "Открыть Фею в Telegram",
    note: "Фея откроет личную серверную комнату именно этого проекта и уровня.",
  };
}

