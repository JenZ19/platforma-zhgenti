export function buildOriginalMobileQuest(
  project: ProjectDefinition,
  mode: DataMode,
  customization: QuestCustomization,
): MobileQuestStep[] | undefined {
  if (project.slug !== "family-expenses") return undefined;
  return buildFamilyExpensesQuest(project, mode, customization).map((step) => {
    const action = actionFor(step.id);
    return {
      ...step,
      action: mobileActions[step.id - 1],
      prompt: `МОБИЛЬНЫЙ ПУТЬ. Ученица работает только через Telegram, личный Codex на сервере и мобильный предпросмотр. Не проси открывать локальную папку телефона и не показывай служебные данные сервера.\n\n${step.prompt}`,
      screenshot: `/screens-mobile/${project.slug}/step-${String(step.id).padStart(2, "0")}.png`,
      guide: undefined,
      help: {
        ...step.help,
        body: `${step.help.body} Если не видно нужной кнопки, вернитесь в Telegram и напишите Фее: «Объясни этот уровень одним нажатием».`,
      },
      mobileAction: action,
    };
  });
}
