def build_prompt(channel: Channel, items: list[dict], facts: list[dict],
                 recent_hooks: list[str], *, count: int, mode: str = "daily",
                 scripts: list[dict] | None = None) -> list[dict]:
    """Промпт на пачку постов. Если передан scripts — это пачка «по сценариям»:
    ровно один пост на каждый сценарий из Google-таблицы, count игнорируется."""
    scripts = list(scripts or [])
    if scripts:
        return _build_scripts_prompt(channel, scripts, facts, recent_hooks, mode=mode)
    return _build_news_prompt(channel, items, facts, recent_hooks, count=count, mode=mode)


def _blocks(facts: list[dict], recent_hooks: list[str]) -> tuple[str, str]:
    facts_block = "\n".join(f"- {f['text']}" for f in facts) if facts else "(нет)"
    hooks_block = "\n".join(f"- {h}" for h in recent_hooks) if recent_hooks else "(нет)"
    return facts_block, hooks_block


def _build_scripts_prompt(channel: Channel, scripts: list[dict], facts: list[dict],
                          recent_hooks: list[str], *, mode: str) -> list[dict]:
    facts_block, hooks_block = _blocks(facts, recent_hooks)
    lines = []
    for sc in scripts:
        title = (sc.get("title") or "").replace("\n", " ").strip()[:200]
        body = (sc.get("text") or "").strip()[:3500]
        lines.append(f"--- СЦЕНАРИЙ id={sc.get('url', '')}\n"
                     f"Хук из съёмки: {title}\n{body}")
    scripts_block = "\n\n".join(lines)

    system = (
        "Ты — SMM-редактор, пишешь готовые посты для соцсети Threads на русском.\n"
        f"Голос канала {channel.handle}:\n{channel.style}\n\n"
        "Задача: перед тобой сценарии снятых рилсов — это НАШИ собственные тексты. "
        "Переупакуй каждый в пост для Threads.\n"
        "Правила:\n"
        + ONE_FIELD_RULES
        + f"- Ровно {len(scripts)} постов: по одному на каждый сценарий, в том же порядке.\n"
        "- Сохраняй фактуру сценария: инструменты, шаги, цифры, названия, порядок мыслей. "
        "Ничего не выдумывай сверх сценария.\n"
        "- Выбрасывай всё, что относится к съёмке и другим соцсетям: «Кадр 1», «хук "
        "дословно», «вот как это настроить, смотри на экран», «напиши в комментариях», "
        "«пришлю в директ», кодовые слова, отсылки к рилсу и монтажу.\n"
        "- НАЧАЛО текста — самая сильная мысль сценария, конкретная, без воды. "
        "СЕРЕДИНА — суть по шагам: что сделать, чем, что получится.\n"
        + HOOK_RULES
        + VIRAL_RULES
        + ATTRIBUTION_RULES
        + EMOTION_RULES
        + "- КОНЦОВКА — короткая живая подводка в телеграм-канал по теме этого "
        "поста (где лежит разбор, промпты, инструкции). Ссылку подставит система: "
        "в текст её НЕ вписывай и не пиши «ссылка ниже/в шапке».\n"
        "- НЕ используй риторическое противопоставление вида «Это не …, это …», "
        "«Дело не в …, а в …» — формулируй мысль прямо, одним утверждением.\n"
        "- НЕ дроби текст на короткие рубленые обрывки ради эффекта (парцелляция). "
        "Пиши законченными связными предложениями.\n"
        "- Поле \"source\": ТОЧНОЕ значение id= того сценария, из которого сделан пост.\n"
        + ("Это ПЕРЕГЕНЕРАЦИЯ: прошлый комплект забракован, зайди с другой стороны.\n"
           if mode == "regen" else "")
        + CHECKLIST
        + "Ответ — СТРОГО JSON без markdown:\n"
        + JSON_SHAPE + "\n"
        "text — весь пост целиком одним полем."
    )
    user = (
        f"Тема канала: {channel.topic}.\n\n"
        f"=== Сценарии ({len(scripts)}) ===\n{scripts_block}\n\n"
        f"=== Факты (ручные знания) ===\n{facts_block}\n\n"
        f"=== Уже присланные хуки (не повторяй дословно) ===\n{hooks_block}\n"
    )
    return [{"role": "system", "content": system}, {"role": "user", "content": user}]


def _build_news_prompt(channel: Channel, items: list[dict], facts: list[dict],
                       recent_hooks: list[str], *, count: int, mode: str) -> list[dict]:
    items = list(items)[:40]  # cap on 40 items
    lines_items = []
    for it in items:
        tag = ("СВОЁ (можно использовать напрямую)" if it.get("own")
               else "ЧУЖОЕ (только фактура! перепиши с нуля под стиль, без цитат)")
        body = (it.get("text") or "").strip().replace("\n", " ")[:800]
        title = (it.get("title") or "").replace("\n", " ").strip()[:200]
        url = (it.get("url") or "").strip()
        line = f"- [{it.get('kind', '')}] {tag}\n  {title}\n  {body}".rstrip()
        # Только настоящие http(s)-ссылки: синтетические trend:// в текст не пускаем.
        if url.startswith(("http://", "https://")):
            line += f"\n  URL: {url}"
        lines_items.append(line)
    items_block = ("\n".join(lines_items) if lines_items
                   else "(свежих материалов нет — опирайся на вечнозелёные темы)")

    facts_block = "\n".join(f"- {f['text']}" for f in facts) if facts else "(нет)"
    hooks_block = "\n".join(f"- {h}" for h in recent_hooks) if recent_hooks else "(нет)"

    angles_block = ""
    if channel.angles:
        angles_block = ("\nБанк ракурсов (ротируй между днями, не повторяй один и тот же):\n"
                        + "\n".join(f"- {a}" for a in channel.angles))

    news = min(channel.news_count, count)
    evergreen = count - news

    mode_note = {
        "daily": "",
        "regen": "Это ПЕРЕГЕНЕРАЦИЯ: прошлый комплект забракован. Дай полностью другие темы.",
        "more": "Это ДОБАВКА к уже присланному: не повторяй прошлые хуки, дай свежие ракурсы.",
    }.get(mode, "")

    system = (
        "Ты — SMM-редактор, пишешь готовые посты для соцсети Threads на русском.\n"
        f"Голос канала {channel.handle}:\n{channel.style}\n{angles_block}\n\n"
        "Правила:\n"
        + ONE_FIELD_RULES
        + "- Структура каждого поста: НАЧАЛО цепляет боль или острый "
        "вопрос аудитории — конкретно, без воды, чтобы человек узнал свою "
        "ситуацию. СЕРЕДИНА даёт реальную пользу: разбор, шаги, цифры, "
        "примеры — интересно и по делу.\n"
        + HOOK_RULES
        + VIRAL_RULES
        + HONESTY_RULES
        + ATTRIBUTION_RULES
        + EMOTION_RULES
        + ENGAGE_RULES
        +         "- КОНЦОВКА: если пост ведёт к НАШЕМУ материалу (СВОЁ) — короткая "
        "подводка (≤ 300 символов) к нему, ссылку подставит система. Если пост "
        "на основе ЧУЖОГО — просто сильное завершение с пользой, система "
        "сама добавит строку «Источник».\n"
        f"- Верни РОВНО {count} постов.\n"
        f"- Примерно {news} постов опирай на свежие материалы (новости ниже), "
        f"{evergreen} — вечнозелёные (личный опыт, мнения, гайды, провокации).\n"
        "- СВОИ (СВОЁ) материалы можно брать почти напрямую, лишь адаптируя под "
        "голос канала. ЧУЖИЕ (ЧУЖОЕ) — жёстко перепиши с нуля, НЕ копируй "
        "формулировки и структуру, НЕ называй источник в тексте (его добавит "
        "система отдельной строкой).\n"
        "- ЛЮБОЙ пост обязан иметь личный слой: что автор с этим уже сделал(а), где проверил(а), что это меняет в его(её) работе, с чем сравнивает. Голого пересказа новости быть не должно.\n"
        "- Если подходящего личного опыта в блоке «Факты» нет — НЕ выдумывай кейсы, суммы и результаты. Пиши честную реакцию практика: что попробуешь первым, какой свой инструмент это заменит, чего опасаешься, сколько времени это экономило бы в похожей задаче.\n"
        "- Чужой пост, который продаёт: реклама, анонс конференции или вебинара, "
        "набор в комьюнити, промокоды и скидки, продажа чужого курса или продукта, "
        "приглашение на чужой канал — НЕ бери в работу вообще. Из чужих источников "
        "берём только пользу: метод, разбор, цифры, кейс, наблюдение.\n"
        "- НЕ используй риторическое противопоставление вида «Это не …, это …», "
        "«Дело не в …, а в …», «не про …, а про …» — формулируй мысль прямо, "
        "одним утверждением.\n"
        "- НЕ дроби текст на короткие рубленые обрывки ради эффекта (парцелляция). "
        "Пиши законченными связными предложениями, а не цепочкой обрубков.\n"
        "- Не повторяй темы из списка «уже присланные хуки».\n"
        "- Поле \"source\": ТОЧНЫЙ URL основного материала из списка выше, на "
        "котором построен пост (СВОЁ или ЧУЖОЕ), либо \"\" если пост "
        "вечнозелёный и ни на чём конкретном не основан.\n"
        f"{mode_note}\n"
        + CHECKLIST
        + "Ответ — СТРОГО JSON без markdown:\n"
        + JSON_SHAPE + "\n"
        "text — весь пост целиком одним полем."
    )
    user = (
        f"Тема канала: {channel.topic}.\n\n"
        f"=== Свежие материалы ===\n{items_block}\n\n"
        f"=== Факты (ручные знания) ===\n{facts_block}\n\n"
        f"=== Уже присланные хуки (НЕ повторять) ===\n{hooks_block}\n"
    )
    return [{"role": "system", "content": system}, {"role": "user", "content": user}]


def _hook_of(text: str) -> str:
    """Начало поста — для истории и списка «не повторяй прошлые хуки»."""
    first = next((ln.strip() for ln in text.splitlines() if ln.strip()), text.strip())
    return first[:HOOK_LEN]


def _text_of(raw: dict, i: int) -> str:
    """Текст поста. Старый формат hook+replies склеиваем в один текст —
    чтобы ответ модели, съехавший на прежнюю схему, не ронял залп."""
    text = raw.get("text")
    if isinstance(text, str) and text.strip():
        return text.strip()
    hook = raw.get("hook")
    replies = raw.get("replies", [])
    if isinstance(hook, str) and hook.strip():
        if not isinstance(replies, list) or not all(isinstance(r, str) for r in replies):
            replies = []
        parts = [hook.strip()] + [r.strip() for r in replies if r.strip()]
        return "\n\n".join(parts)
    raise ComposeError(f"пост {i}: пустой text")


def parse_threads(content: str) -> list[dict]:
    idx = content.find("{")
    if idx == -1:
        raise ComposeError("в ответе нет JSON-объекта")
    try:
        data, _ = json.JSONDecoder().raw_decode(content[idx:])
    except json.JSONDecodeError as e:
        raise ComposeError(f"ответ не является JSON: {e}") from e
    threads = data.get("threads") if isinstance(data, dict) else None
    if not isinstance(threads, list) or not threads:
        raise ComposeError("в JSON нет непустого массива threads")
    out: list[dict] = []
    for i, t in enumerate(threads):
        if not isinstance(t, dict):
            raise ComposeError(f"пост {i}: не объект")
        text = _text_of(t, i)
        source = t.get("source", "")
        if not isinstance(source, str):
            source = ""
        out.append({"text": text, "hook": _hook_of(text), "source": source.strip()})
    return out


def _pre(s: str) -> str:
    return f"<pre>{_html.escape(s)}</pre>"


def _tail(cta_link: str | None, source_link: str | None) -> str:
    """Подпись ПОД блоком поста. Ссылка внутри текста режет охват в Threads,
    поэтому её место — первый комментарий. Блок <pre> копируется в один тап и
    содержит ровно то, что уходит в пост, без ссылки."""
    if cta_link:
        return f"\n↓ первым комментарием: {cta_link}"
    if source_link:
        return f"\n↓ источник, первым комментарием: {source_link}"
    return ""


def format_thread(thread: dict, cta_link: str | None = None,
                  source_link: str | None = None) -> str:
    text = thread.get("text") or _text_of(thread, 0)
    return _pre(text) + _tail(cta_link, source_link)


def format_thread_message(thread: dict, cta_link: str | None = None,
                          source_link: str | None = None) -> list[str]:
    text = thread.get("text") or _text_of(thread, 0)
    tail = _tail(cta_link, source_link)
    chunks = split_message(_pre(text))
    if tail:
        if len(chunks[-1]) + len(tail) <= TG_LIMIT:
            chunks[-1] += tail
        else:
            chunks.append(tail.lstrip("\n"))
    return chunks


def _split_pre(inner: str, limit: int) -> list[str]:
    """Режем длинный пост по абзацам, затем по строкам, в последнюю очередь —
    по символам. Каждый кусок — самостоятельный <pre>-блок."""
    inner_limit = limit - len("<pre></pre>")
    if inner_limit <= 0:
        return [inner[i:i + limit] for i in range(0, len(inner), limit)]

    def chunks_by(sep: str, s: str) -> list[str]:
        out: list[str] = []
        cur = ""
        for part in s.split(sep):
            piece = part if not cur else sep + part
            if cur and len(cur) + len(piece) > inner_limit:
                out.append(cur)
                cur = part
            else:
                cur += piece
        if cur:
            out.append(cur)
        return out

    pieces = chunks_by("\n\n", inner)
    refined: list[str] = []
    for p in pieces:
        refined.extend(chunks_by("\n", p) if len(p) > inner_limit else [p])
    final: list[str] = []
    for p in refined:
        while len(p) > inner_limit:
            final.append(p[:inner_limit])
            p = p[inner_limit:]
        if p:
            final.append(p)
    return final


def split_message(text: str, limit: int = TG_LIMIT) -> list[str]:
    if len(text) <= limit:
        return [text]
    if text.startswith("<pre>") and text.endswith("</pre>"):
        return [f"<pre>{c}</pre>" for c in _split_pre(text[5:-6], limit)]
    return [text[i:i + limit] for i in range(0, len(text), limit)]


def format_threads(threads: list[dict]) -> list[str]:
    msgs: list[str] = []
    for t in threads:
        msgs.extend(split_message(format_thread(t)))
    return msgs
